-- Dữ liệu cấp CÔNG TY (ptInfo, bgOrg) tách khỏi project_data_entries: trước đây nằm chung bảng
-- dưới mã dự án giả '__cty:<company_id>' / '__cty' / '__cty:0', khiến project_data_entries không
-- thể có khoá ngoại tới projects.
-- company_id NULL = cấu hình không thuộc công ty nào (super admin chưa chọn công ty; trước là mã '__cty:0').
create table company_settings (
  id            bigint generated by default as identity,
  company_id    uuid,
  setting_key   text not null,
  setting_value jsonb,
  updated_at    timestamptz not null default now(),
  updated_by    text,
  constraint pk_company_settings primary key (id),
  constraint uq_company_settings_company_id_setting_key unique nulls not distinct (company_id, setting_key),
  constraint fk_company_settings_company_id foreign key (company_id) references companies (id) on delete cascade,
  constraint ck_company_settings_setting_key check (setting_key <> '')
);
comment on table company_settings is 'Per-company key/value documents (was: project_data_entries rows under the pseudo project codes ''__cty:<company_id>'', ''__cty'', ''__cty:0'').';
comment on column company_settings.company_id is 'Owning company; NULL = not tied to any company (super admin with no company selected).';
comment on column company_settings.setting_key is 'Document key, e.g. ptInfo (work-item info), bgOrg (company profile printed on quotations).';
comment on column company_settings.setting_value is 'JSON document; replaced as a whole on every save.';
comment on column company_settings.updated_by is 'Username of the last editor.';

-- 1) mã '__cty:<uuid công ty còn tồn tại>'
insert into company_settings (company_id, setting_key, setting_value, updated_at, updated_by)
  select c.id, e.data_key, e.data_value, coalesce(e.updated_at, now()), e.updated_by
  from project_data_entries e join companies c on e.project_code = '__cty:' || c.id::text
  on conflict do nothing;
-- 2) mã cũ '__cty' có gắn công ty: chỉ lấy khi công ty đó chưa có khoá này (bản '__cty:<id>' được ưu tiên như code cũ)
insert into company_settings (company_id, setting_key, setting_value, updated_at, updated_by)
  select e.company_id, e.data_key, e.data_value, coalesce(e.updated_at, now()), e.updated_by
  from project_data_entries e where e.project_code = '__cty' and e.company_id is not null
    and exists (select 1 from companies c where c.id = e.company_id)
  on conflict do nothing;
-- 3) không thuộc công ty nào: '__cty:0' rồi tới '__cty'
insert into company_settings (company_id, setting_key, setting_value, updated_at, updated_by)
  select null, e.data_key, e.data_value, coalesce(e.updated_at, now()), e.updated_by
  from project_data_entries e where e.company_id is null and e.project_code in ('__cty:0', '__cty')
  order by (e.project_code = '__cty:0') desc
  on conflict do nothing;
-- các dòng mã giả còn lại (vd '__cty:<uuid công ty đã xoá>') được cách ly ở migration sau cùng các dòng mồ côi khác
delete from project_data_entries e
  where e.project_code in ('__cty', '__cty:0')
     or exists (select 1 from companies c where e.project_code = '__cty:' || c.id::text);
