-- purchase_proposal_items chứa 2 loại dòng khác nghĩa (cùng cột mang ý khác nhau theo loại phiếu):
--   phiếu 'ck' (xin chiết khấu NCC): mỗi dòng là 1 sản phẩm
--   phiếu 'tt' (đề xuất thanh toán): mỗi dòng là 1 đợt thanh toán
-- Tách thành 2 bảng, mỗi bảng một nhiệm vụ. Cả hai chỉ liên kết với phiếu cha bằng proposal_code.
create table proposal_discount_items (
  id                  bigint generated by default as identity,
  proposal_code       text not null,
  sort_order          integer default 0,
  product_code        text,
  product_name        text,
  brand               text,
  room                text,
  unit                text,
  quantity            numeric default 0,
  original_unit_price numeric default 0,
  rate_pct            numeric default 0,
  unit_price          numeric default 0,
  amount              numeric default 0,
  image_urls          text,
  constraint pk_proposal_discount_items primary key (id),
  constraint fk_proposal_discount_items_proposal_code foreign key (proposal_code) references purchase_proposals (proposal_code) on delete cascade,
  constraint ck_proposal_discount_items_sort_order check (sort_order >= 0),
  constraint ck_proposal_discount_items_quantity check (quantity >= 0),
  constraint ck_proposal_discount_items_original_unit_price check (original_unit_price >= 0),
  constraint ck_proposal_discount_items_unit_price check (unit_price >= 0),
  constraint ck_proposal_discount_items_amount check (amount >= 0)
);
create index idx_proposal_discount_items_proposal_code_sort_order on proposal_discount_items (proposal_code, sort_order);
comment on table proposal_discount_items is 'Product lines of a discount proposal (purchase_proposals.proposal_type = ''ck''). Immutable snapshot. Company = company of the parent proposal.';
comment on column proposal_discount_items.product_code is 'Product code snapshot (soft reference - no FK by design).';
comment on column proposal_discount_items.original_unit_price is 'Unit price before the proposed discount.';
comment on column proposal_discount_items.rate_pct is 'Proposed supplier discount, percent.';
comment on column proposal_discount_items.unit_price is 'Unit price after the proposed discount.';
comment on column proposal_discount_items.amount is 'round(quantity * unit_price).';

create table proposal_payment_installments (
  id            bigint generated by default as identity,
  proposal_code text not null,
  sort_order    integer default 0,
  label         text,
  rate_pct      numeric default 0,
  amount        numeric default 0,
  due_date      date,
  note          text,
  constraint pk_proposal_payment_installments primary key (id),
  constraint fk_proposal_payment_installments_proposal_code foreign key (proposal_code) references purchase_proposals (proposal_code) on delete cascade,
  constraint ck_proposal_payment_installments_sort_order check (sort_order >= 0),
  constraint ck_proposal_payment_installments_amount check (amount >= 0)
);
create index idx_proposal_payment_installments_proposal_code_sort_order on proposal_payment_installments (proposal_code, sort_order);
comment on table proposal_payment_installments is 'Instalments of a payment proposal (purchase_proposals.proposal_type = ''tt''). Immutable snapshot. Company = company of the parent proposal.';
comment on column proposal_payment_installments.label is 'Instalment label, e.g. ''Đợt 1''.';
comment on column proposal_payment_installments.rate_pct is 'Share of the order total paid in this instalment, percent.';
comment on column proposal_payment_installments.amount is 'Instalment amount.';
comment on column proposal_payment_installments.due_date is 'Expected payment date.';

-- chuyển dữ liệu cũ theo loại của phiếu cha
insert into proposal_discount_items (id, proposal_code, sort_order, product_code, product_name, brand, room, unit,
                                     quantity, original_unit_price, rate_pct, unit_price, amount, image_urls)
  select i.id, i.proposal_code, i.sort_order, i.product_code, i.product_name, i.brand, i.room, i.unit,
         i.quantity, i.original_unit_price, i.rate_pct, i.unit_price, i.amount, i.image_urls
  from purchase_proposal_items i join purchase_proposals p on p.proposal_code = i.proposal_code
  where p.proposal_type is distinct from 'tt';
insert into proposal_payment_installments (proposal_code, sort_order, label, rate_pct, amount, due_date, note)
  select i.proposal_code, i.sort_order, i.product_name, i.rate_pct, i.amount, i.expected_payment_date, i.note
  from purchase_proposal_items i join purchase_proposals p on p.proposal_code = i.proposal_code
  where p.proposal_type = 'tt';
select setval(pg_get_serial_sequence('proposal_discount_items', 'id'), coalesce((select max(id) from proposal_discount_items), 0) + 1, false);

drop table purchase_proposal_items;
